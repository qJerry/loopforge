def _detect_project_group_children(root: Path) -> list[Dict[str, str]]:
    if not root.is_dir():
        return []
    children: list[Dict[str, str]] = []
    for child in sorted(root.iterdir(), key=lambda path: path.name):
        if not child.is_dir() or not (child / ".git").exists():
            continue
        children.append({"key": child.name, "path": str(child.resolve()), "repo": child.name})
    return children


def _normalize_project_group_children(
    root: Path,
    raw_children: list[Dict[str, Any]],
    blockers: list[Dict[str, str]],
) -> list[Dict[str, str]]:
    children: list[Dict[str, str]] = []
    seen: set[str] = set()
    for index, raw in enumerate(raw_children):
        payload = raw if isinstance(raw, dict) else {}
        key = str(payload.get("key") or payload.get("id") or "").strip()
        path_value = str(payload.get("path") or payload.get("root_dir") or "").strip()
        if not key or not path_value:
            blockers.append(_blocker("project_group_child_invalid", f"第 {index + 1} 个子仓必须提供 key 和 path。"))
            continue
        if key in seen:
            blockers.append(_blocker("project_group_child_duplicate", f"项目组子仓 key 重复：{key}"))
            continue
        seen.add(key)
        path = Path(path_value).expanduser()
        if not path.is_absolute():
            path = root / path
        path = path.resolve()
        if not path.is_dir() or not (path / ".git").exists():
            blockers.append(_blocker("project_group_child_not_git", f"项目组子仓不是可用 Git 仓库：{path}"))
            continue
        children.append({"key": key, "path": str(path), "repo": str(payload.get("repo") or path.name)})
    return children


def _register_profile(config_path: Path | None, entry: Dict[str, Any]) -> None:
    payload = read_projects_config(config_path)
    projects = payload.setdefault("projects", [])
    if not isinstance(projects, list):
        raise ValueError("projects 配置必须是列表")
    entry_root = Path(str(entry["root_dir"])).resolve()
    for current in projects:
        if not isinstance(current, dict):
            continue
        current_id = str(current.get("id") or current.get("project_id") or "")
        current_root_value = current.get("root_dir") or current.get("root")
        current_root = Path(str(current_root_value)).expanduser().resolve() if current_root_value else None
        if current_id == entry["id"] and current_root == entry_root:
            current.pop("project_type", None)
            current.pop("bdd", None)
            registration_keys = (
                "name",
                "planning_adapter",
                "automation_mode",
                "schedule_enabled",
                "auto_commit",
                "worktree_managed",
            )
            current.update({key: entry[key] for key in registration_keys if key in entry})
            if "project_group" in entry:
                current["project_group"] = entry["project_group"]
            write_projects_config(payload, config_path)
            return
        if current_id == entry["id"]:
            raise ValueError(f"项目 id 已被其他目录占用：{entry['id']}")
        if current_root == entry_root:
            raise ValueError(f"项目目录已登记为其他项目：{current_id}")
    projects.append(entry)
    write_projects_config(payload, config_path)


def _validate_registration(config_path: Path | None, entry: Dict[str, Any]) -> None:
    payload = read_projects_config(config_path)
    projects = payload.get("projects")
    if not isinstance(projects, list):
        raise ValueError("projects 配置必须是列表")
    entry_root = Path(str(entry["root_dir"])).resolve()
    for current in projects:
        if not isinstance(current, dict):
            continue
        current_id = str(current.get("id") or current.get("project_id") or "")
        current_root_value = current.get("root_dir") or current.get("root")
        current_root = Path(str(current_root_value)).expanduser().resolve() if current_root_value else None
        if current_id == entry["id"] and current_root != entry_root:
            raise ValueError(f"项目 id 已被其他目录占用：{entry['id']}")
        if current_root == entry_root and current_id != entry["id"]:
            raise ValueError(f"项目目录已登记为其他项目：{current_id}")


