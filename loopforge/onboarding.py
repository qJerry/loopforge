def _reconcile_agents(current: str | None, generated: str, required_docs: tuple[str, ...]) -> str:
    if current is None or not current.strip():
        return generated
    legacy_pattern = re.compile(
        re.escape(LEGACY_AGENTS_START) + r".*?" + re.escape(LEGACY_AGENTS_END),
        re.DOTALL,
    )
    without_legacy = legacy_pattern.sub("", current)
    if without_legacy != current:
        without_legacy = re.sub(r"\n{3,}", "\n\n", without_legacy).strip()
        if not without_legacy:
            return generated
        base = without_legacy + "\n"
    else:
        base = current
    missing = [path for path in required_docs if path not in base]
    if not missing:
        return base
    lines = ["## Agent 文档路由", "", "修改代码前，按任务涉及范围补充阅读：", ""]
    lines.extend(f"- `{path}`" for path in missing)
    lines.extend(
        [
            "",
            "Dev Task 的详细执行合同只在 `agent_docs/DEV_TASK_EXECUTION.md` 维护，本文件不重复字段与状态规则。",
        ]
    )
    return base.rstrip() + "\n\n" + "\n".join(lines) + "\n"


def _load_manifest() -> Dict[str, Any]:
    profiles: Dict[str, Any] = {}
    for path in sorted(TEMPLATE_ROOT.glob("*/manifest.json")):
        profile = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(profile, dict):
            raise ValueError(f"onboarding manifest 必须是对象：{path}")
        profile_type = str(profile.get("type") or path.parent.name).strip()
        if profile_type != path.parent.name or profile_type in profiles:
            raise ValueError(f"onboarding profile 类型与目录不一致或重复：{profile_type}")
        profile["type"] = profile_type
        profiles[profile_type] = profile
    return {"version": 2, "profiles": profiles}


def _render(relative_template: str, variables: Dict[str, str]) -> str:
    template_path = (TEMPLATE_ROOT / relative_template).resolve()
    if not template_path.is_relative_to(TEMPLATE_ROOT.resolve()):
        raise ValueError(f"模板路径越界：{relative_template}")
    text = template_path.read_text(encoding="utf-8")
    for key, value in variables.items():
        text = text.replace("{{" + key + "}}", value)
    unresolved = re.findall(r"\{\{[A-Z0-9_]+\}\}", text)
    if unresolved:
        raise ValueError(f"模板存在未替换变量：{', '.join(sorted(set(unresolved)))}")
    return text.rstrip() + "\n"


def _is_generated(content: str) -> bool:
    return any(marker in content for marker in GENERATED_MARKERS)


def _detect_package_manager(root: Path) -> str:
    package = _read_json(root / "package.json")
    declared = str(package.get("packageManager") or "") if isinstance(package, dict) else ""
    if declared:
        return declared.split("@", 1)[0]
    for marker, manager in (("pnpm-lock.yaml", "pnpm"), ("yarn.lock", "yarn"), ("package-lock.json", "npm")):
        if (root / marker).is_file():
            return manager
    return "npm"


def _detect_flutter_build_target(root: Path) -> str:
    targets = [name for name in ("android", "web", "ios", "macos", "linux", "windows") if (root / name).is_dir()]
    if len(targets) != 1:
        return ""
    return {"android": "apk", "web": "web"}.get(targets[0], targets[0])


def _detect_java_build_tool(root: Path) -> str:
    if (root / "mvnw").is_file() or (root / "pom.xml").is_file():
        return "maven"
    if any((root / name).is_file() for name in ("gradlew", "build.gradle.kts", "build.gradle")):
        return "gradle"
    return ""


def _resolve_planning_adapter(root: Path, explicit: str, blockers: list[Dict[str, str]]) -> str:
    selected = str(explicit or "").strip() or DEFAULT_PLANNING_ADAPTER
    if selected not in PLANNING_ADAPTERS:
        blockers.append(
            _blocker(
                "planning_adapter_invalid",
                "不支持的研发工作流：" + selected + "；可选值：" + ", ".join(sorted(PLANNING_ADAPTERS)),
            )
        )
        return selected
    return selected


