def _read_optional(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None


def _read_json(path: Path) -> Any:
    raw = _read_optional(path)
    if raw is None:
        return None
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        return None


def _digest(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def _slug(value: str) -> str:
    clean = re.sub(r"[^a-zA-Z0-9_-]+", "-", str(value).strip()).strip("-").lower()
    return clean or "project"


def _blocker(code: str, summary: str, path: str = "") -> Dict[str, str]:
    blocker = {"code": code, "summary": summary}
    if path:
        blocker["path"] = path
    return blocker


def _add_check(checks: list[Dict[str, Any]], check_id: str, passed: bool, summary: str) -> None:
    checks.append({"id": check_id, "status": "passed" if passed else "failed", "summary": summary})
